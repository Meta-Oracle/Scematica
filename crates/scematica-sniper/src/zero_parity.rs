//! The numbers Scematica Zero must reproduce, emitted by the bot that owns them.
//!
//! `web/lib/zero/` runs the sniper's decision logic in a browser tab. It cannot link this
//! crate — solana-sdk does not compile to a page, and the pin comments in the root
//! `Cargo.toml` explain why the HTTP stack a browser build wants cannot coexist with it
//! anyway — so the logic is ported to TypeScript. Two implementations of one edge drift
//! unless that is managed, and the drift is silent: a mis-ported stop-loss does not throw,
//! it holds a losing position five percent longer.
//!
//! So this module emits every constant and every formula result Zero depends on, and
//! `web/scripts/check-zero.mjs` asserts the TypeScript reproduces them exactly. The
//! fixture is generated by the same code the sniper compiles — not typed out beside it —
//! which is the difference between this and a comment saying "keep these in sync".
//!
//! **Rust is authoritative.** A number changed here is a number Zero must follow, and the
//! test below fails until the fixture is regenerated:
//!
//!   cargo test -p scematica-sniper zero_parity                      (verify)
//!   ZERO_PARITY_WRITE=1 cargo test -p scematica-sniper zero_parity  (regenerate)
//!
//! ## What this pins, and what it does not
//!
//! It pins **values**: config constants, the rate-mode table, `KellySizer::compute_multiplier`
//! over a grid of histories, `coherence::assess` over a grid of degradations, the adaptive
//! pullback curve, and `PoolScorer::score` over a grid of pools.
//!
//! It does **not** pin control flow. The sell monitor's exit ladder is four hundred lines
//! inline in an async loop in `sniper.rs`; extracting it into a callable function would be
//! a large diff in a live buy-and-sell path, which is how a trading bug gets introduced by
//! a diagnostic. Zero's `exit-ladder.ts` is a hand port of that loop, and the gap between
//! the two is real — the same gap `scema-lean`'s README refuses to paper over. What the
//! fixture removes is the larger half of the risk: every threshold the ladder branches on
//! is checked here, so a ported rule can be wrong about *order* but not about *where it
//! fires*.

