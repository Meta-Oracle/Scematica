/// Where the fixture lands. Read by `web/scripts/check-zero.mjs`.
fn fixture_path() -> PathBuf {
    // CARGO_MANIFEST_DIR is `crates/scematica-sniper`.
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../web/lib/zero/fixtures/sniper-parity.json")
}

fn config_toml_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../config.toml")
}

